-- Schema inicial do Rota Vital, equivalente ao que o Hibernate gerava com ddl-auto
-- antes da alocação persistida (main até o PR #21).
-- Em bancos já existentes esta versão é marcada como baseline e não é executada.
--
-- Os enums ficam em VARCHAR sem CHECK: os valores já são garantidos pelo
-- @Enumerated(EnumType.STRING) e o CHECK ... IN (...) quebra no H2 2.4 quando a
-- conexão que rodou a migration é fechada ("The database has been closed").

CREATE TABLE solicitacao_sangue (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_hospital   VARCHAR(255) NOT NULL,
    tipo_sanguineo  VARCHAR(255) NOT NULL,
    tipo_componente VARCHAR(255) NOT NULL,
    quantidade      INTEGER      NOT NULL,
    nivel_urgencia  VARCHAR(255) NOT NULL,
    status          VARCHAR(255) NOT NULL
);

CREATE TABLE bolsa (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador   VARCHAR(255) NOT NULL,
    tipo_sanguineo  VARCHAR(255) NOT NULL,
    tipo_componente VARCHAR(255) NOT NULL,
    data_coleta     DATE         NOT NULL,
    data_validade   DATE         NOT NULL,
    volume          INTEGER      NOT NULL,
    status          VARCHAR(255) NOT NULL,
    CONSTRAINT uk_bolsa_identificador UNIQUE (identificador)
);

CREATE TABLE baixa_bolsa (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolsa_id   BIGINT       NOT NULL,
    motivo     VARCHAR(255) NOT NULL,
    data_baixa DATE         NOT NULL,
    automatica BOOLEAN      NOT NULL,
    CONSTRAINT fk_baixa_bolsa_bolsa FOREIGN KEY (bolsa_id) REFERENCES bolsa (id)
);
