-- Rede de distribuição e rotas (história 3).
-- local_rede são os vértices do grafo (hemocentro e hospitais) e trecho as arestas,
-- de mão dupla, com o tempo de viagem (peso do caminho mínimo) e a distância.
-- Os dados da rede são sintéticos, inspirados na Região Metropolitana do Recife.

CREATE TABLE local_rede (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    tipo VARCHAR(255) NOT NULL,
    CONSTRAINT uk_local_rede_nome UNIQUE (nome)
);

CREATE TABLE trecho (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem_id     BIGINT           NOT NULL,
    destino_id    BIGINT           NOT NULL,
    tempo_minutos INTEGER          NOT NULL,
    distancia_km  DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_trecho_origem FOREIGN KEY (origem_id) REFERENCES local_rede (id),
    CONSTRAINT fk_trecho_destino FOREIGN KEY (destino_id) REFERENCES local_rede (id)
);

-- caminho: ids dos locais percorridos, separados por vírgula.
-- entregas: "localId@minutoDeChegada" de cada hospital, na ordem de visita.
CREATE TABLE rota (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem_id           BIGINT           NOT NULL,
    caminho             VARCHAR(2000)    NOT NULL,
    entregas            VARCHAR(2000)    NOT NULL,
    tempo_total_minutos INTEGER          NOT NULL,
    distancia_total_km  DOUBLE PRECISION NOT NULL,
    janela_minutos      INTEGER          NOT NULL,
    status              VARCHAR(255)     NOT NULL,
    criada_em           TIMESTAMP        NOT NULL,
    CONSTRAINT fk_rota_origem FOREIGN KEY (origem_id) REFERENCES local_rede (id)
);

