-- Monitoramento da cadeia fria (história 6).
-- remessa é a carga em trânsito com um sensor de temperatura; leitura_temperatura
-- guarda o histórico para auditoria (leitura_id único descarta reenvios do sensor);
-- alerta_remessa registra excursão térmica, leituras perdidas e sensor sem sinal.

CREATE TABLE remessa (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rota_id              BIGINT,
    tipo_componente      VARCHAR(255) NOT NULL,
    sensor_id            VARCHAR(255) NOT NULL,
    status               VARCHAR(255) NOT NULL,
    condicao             VARCHAR(255) NOT NULL,
    sensor_indisponivel  BOOLEAN      NOT NULL,
    iniciada_em          TIMESTAMP    NOT NULL,
    ultima_leitura_em    TIMESTAMP,
    ultima_sequencia     BIGINT,
    entregue_em          TIMESTAMP,
    CONSTRAINT fk_remessa_rota FOREIGN KEY (rota_id) REFERENCES rota (id)
);

CREATE TABLE leitura_temperatura (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remessa_id     BIGINT           NOT NULL,
    leitura_id     VARCHAR(255)     NOT NULL,
    sensor_id      VARCHAR(255)     NOT NULL,
    sequencia      BIGINT           NOT NULL,
    temperatura    DOUBLE PRECISION NOT NULL,
    data_hora      TIMESTAMP        NOT NULL,
    recebida_em    TIMESTAMP        NOT NULL,
    dentro_da_faixa BOOLEAN         NOT NULL,
    CONSTRAINT fk_leitura_remessa FOREIGN KEY (remessa_id) REFERENCES remessa (id),
    CONSTRAINT uk_leitura_temperatura_leitura_id UNIQUE (leitura_id)
);

CREATE INDEX idx_leitura_temperatura_remessa_id ON leitura_temperatura (remessa_id);

CREATE TABLE alerta_remessa (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remessa_id BIGINT        NOT NULL,
    tipo       VARCHAR(255)  NOT NULL,
    mensagem   VARCHAR(1000) NOT NULL,
    criado_em  TIMESTAMP     NOT NULL,
    CONSTRAINT fk_alerta_remessa FOREIGN KEY (remessa_id) REFERENCES remessa (id)
);

CREATE INDEX idx_alerta_remessa_remessa_id ON alerta_remessa (remessa_id);
